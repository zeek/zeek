#!/usr/bin/env python3
"""
Generate conn-count-too-large.pcap — a DNS query with qd_count > dns_max_queries.
Set dns_max_queries to e.g. 3 in the test to trigger DNS_Conn_count_too_large.

Generated by Claude Sonnet 4.6 (Anthropic), adapted by Claude Sonnet 5.5
(Anthropic) to use Scapy's DNS layer and a deterministic timestamp.
"""

from pathlib import Path

from scapy.all import DNS, DNSQR, IP, UDP, Ether, wrpcap

SRC = "1.2.3.4"
DST = "5.6.7.8"
SMAC = "02:00:00:00:00:01"
DMAC = "02:00:00:00:00:02"
BASE_TIME = 1_700_000_000.0
NUM_QUESTIONS = 10  # lower dns_max_queries to 3 in the test


def main():
    questions = [DNSQR(qname="example.com", qtype="A", qclass="IN")] * NUM_QUESTIONS
    pkt = (
        Ether(src=SMAC, dst=DMAC)
        / IP(src=SRC, dst=DST)
        / UDP(sport=12345, dport=53)
        / DNS(id=0xABCD, rd=1, qd=questions)
    )
    pkt.time = BASE_TIME

    wrpcap(str(Path(__file__).with_suffix("")), [pkt])


if __name__ == "__main__":
    main()
