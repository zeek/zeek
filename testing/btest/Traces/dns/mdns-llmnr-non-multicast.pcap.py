#!/usr/bin/env python3
"""Generate mDNS/LLMNR traffic to exercise the non-multicast drop in the DNS analyzer.

The DNS analyzer (DNS_Interpreter::ParseMessage) drops a message only when BOTH
the originator and responder are non-multicast AND both endpoints use an mDNS
(5353) or LLMNR (5355) port. This trace walks the port and address combinations
around that condition so the test can confirm which connections are parsed as
DNS and which are silently dropped:

  1. mDNS, both ports 5353, both hosts unicast          -> DROPPED (the fix)
  2. mDNS, both ports 5353, responder multicast          -> parsed (typical mDNS)
  3. mDNS, both ports 5353, both hosts multicast          -> parsed
  4. mDNS, both ports 5353, originator multicast only     -> parsed
  5. mDNS, both ports 5353, IPv6 responder multicast      -> parsed
  6. LLMNR, both ports 5355, both hosts unicast           -> DROPPED (the fix)
  7. LLMNR, both ports 5355, responder multicast          -> parsed
  8. mixed ports, src 5353 / dst 53, both hosts unicast   -> parsed (not both mDNS ports)
  9. mixed ports, src 53 / dst 5353, both hosts unicast   -> parsed (not both mDNS ports)

Only cases 1 and 6 should be suppressed; every other connection should still
produce a dns.log entry. mDNS multicast groups are 224.0.0.251 / ff02::fb and
LLMNR multicast is 224.0.0.252.

Generated by Claude Opus 4.8 (Anthropic).
"""

from pathlib import Path

from scapy.all import DNS, DNSQR, IP, UDP, Ether, IPv6, wrpcap

BASE_TIME = 1_700_000_000.0

MDNS_PORT = 5353
LLMNR_PORT = 5355

ETH_SRC = "00:11:22:33:44:55"
ETH_MCAST4 = "01:00:5e:00:00:fb"
ETH_MCAST6 = "33:33:00:00:00:fb"
ETH_UNICAST = "66:77:88:99:aa:bb"


def dns_query(name):
    # mDNS/LLMNR queries use a zero transaction ID and no recursion desired.
    return DNS(id=0, rd=0, qd=DNSQR(qname=name, qtype="A"))


packets = []


def add(l2_dst, ip_layer, sport, dport, qname):
    pkt = (
        Ether(src=ETH_SRC, dst=l2_dst)
        / ip_layer
        / UDP(sport=sport, dport=dport)
        / dns_query(qname)
    )
    packets.append(pkt)


# 1. mDNS, both ports 5353, both unicast -> DROPPED
add(
    ETH_UNICAST,
    IP(src="192.168.1.10", dst="192.168.1.20"),
    MDNS_PORT,
    MDNS_PORT,
    "drop-mdns-unicast.local",
)

# 2. mDNS, both ports 5353, responder multicast -> parsed (typical mDNS)
add(
    ETH_MCAST4,
    IP(src="192.168.1.11", dst="224.0.0.251"),
    MDNS_PORT,
    MDNS_PORT,
    "mdns-to-multicast.local",
)

# 3. mDNS, both ports 5353, both multicast -> parsed
add(
    ETH_MCAST4,
    IP(src="224.0.0.251", dst="224.0.0.251"),
    MDNS_PORT,
    MDNS_PORT,
    "mdns-both-multicast.local",
)

# 4. mDNS, both ports 5353, originator multicast only -> parsed
add(
    ETH_UNICAST,
    IP(src="224.0.0.251", dst="192.168.1.21"),
    MDNS_PORT,
    MDNS_PORT,
    "mdns-orig-multicast.local",
)

# 5. mDNS, both ports 5353, IPv6 responder multicast -> parsed
add(
    ETH_MCAST6,
    IPv6(src="fe80::1", dst="ff02::fb"),
    MDNS_PORT,
    MDNS_PORT,
    "mdns-ipv6-multicast.local",
)

# 6. LLMNR, both ports 5355, both unicast -> DROPPED
add(
    ETH_UNICAST,
    IP(src="192.168.1.12", dst="192.168.1.22"),
    LLMNR_PORT,
    LLMNR_PORT,
    "drop-llmnr-unicast",
)

# 7. LLMNR, both ports 5355, responder multicast -> parsed
add(
    ETH_MCAST4,
    IP(src="192.168.1.13", dst="224.0.0.252"),
    LLMNR_PORT,
    LLMNR_PORT,
    "llmnr-to-multicast",
)

# 8. mixed ports, src 5353 / dst 53, both unicast -> parsed (not both mDNS ports)
add(
    ETH_UNICAST,
    IP(src="192.168.1.14", dst="192.168.1.24"),
    MDNS_PORT,
    53,
    "mixed-src-mdns.example.com",
)

# 9. mixed ports, src 53 / dst 5353, both unicast -> parsed (not both mDNS ports)
add(
    ETH_UNICAST,
    IP(src="192.168.1.15", dst="192.168.1.25"),
    53,
    MDNS_PORT,
    "mixed-dst-mdns.example.com",
)

for index, p in enumerate(packets):
    p.time = BASE_TIME + index * 0.001

wrpcap(str(Path(__file__).with_suffix("")), packets)
