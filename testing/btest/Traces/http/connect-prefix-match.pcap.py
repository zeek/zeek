#!/usr/bin/env python3
"""
Generate connect-prefix-match.pcap: an HTTP request whose method is a prefix
of "CONNECT".

The bug: HTTP_Analyzer::HTTP_Request() used
strncasecmp(method, "CONNECT", method_len) to detect CONNECT requests. Because
the comparison length was the (short) request method's length, any method that
is a prefix of "CONNECT" — e.g. "CON" — matched. Zeek then treated the
connection as a CONNECT tunnel and stopped analyzing the HTTP inside it,
letting a following "FETCH /secret" request and a bogus response body evade
analysis. The fix also requires method_len == 7 (len("CONNECT")).

Generated by Claude Opus 4.8 (Anthropic).
"""

from pathlib import Path

from scapy.all import IP, TCP, Ether, wrpcap

CLIENT_IP = "10.0.0.1"
SERVER_IP = "10.0.0.2"
CLIENT_PORT = 45678
SERVER_PORT = 80


def pkt(src_ip, dst_ip, sport, dport, flags, seq, ack, payload=b""):
    return (
        Ether(src="00:00:00:00:00:01", dst="00:00:00:00:00:02")
        / IP(src=src_ip, dst=dst_ip)
        / TCP(sport=sport, dport=dport, flags=flags, seq=seq, ack=ack)
        / payload
    )


def cpkt(flags, seq, ack, payload=b""):
    return pkt(CLIENT_IP, SERVER_IP, CLIENT_PORT, SERVER_PORT, flags, seq, ack, payload)


def spkt(flags, seq, ack, payload=b""):
    return pkt(SERVER_IP, CLIENT_IP, SERVER_PORT, CLIENT_PORT, flags, seq, ack, payload)


def build_packets(method):
    connect_request = (method + " host:443 HTTP/1.1\r\nHost: a\r\n\r\n").encode()
    connect_reply = b"HTTP/1.1 200 OK\r\n\r\n"
    tunneled_request = b"FETCH /secret HTTP/1.1\r\nHost: evil.example\r\n\r\n"
    tunneled_reply = b"PWND-4-bytes-of-not-a-status-line"

    c_seq = 1000
    s_seq = 5000

    pkts = []

    # Three-way handshake
    pkts.append(cpkt("S", c_seq, 0))
    c_seq += 1
    pkts.append(spkt("SA", s_seq, c_seq))
    s_seq += 1
    pkts.append(cpkt("A", c_seq, s_seq))

    # Prefix-of-CONNECT request and its reply
    pkts.append(cpkt("PA", c_seq, s_seq, connect_request))
    c_seq += len(connect_request)
    pkts.append(spkt("PA", s_seq, c_seq, connect_reply))
    s_seq += len(connect_reply)
    pkts.append(cpkt("A", c_seq, s_seq))

    # Request/response that must still be analyzed (not tunneled away)
    pkts.append(cpkt("PA", c_seq, s_seq, tunneled_request))
    c_seq += len(tunneled_request)
    pkts.append(spkt("PA", s_seq, c_seq, tunneled_reply))
    s_seq += len(tunneled_reply)
    pkts.append(cpkt("A", c_seq, s_seq))

    # Teardown
    pkts.append(cpkt("FA", c_seq, s_seq))
    c_seq += 1
    pkts.append(spkt("FA", s_seq, c_seq))
    s_seq += 1
    pkts.append(cpkt("A", c_seq, s_seq))

    return pkts


def main():
    out = Path(__file__).with_suffix("")
    pkts = build_packets("CON")
    wrpcap(str(out), pkts)
    print(f"Wrote {len(pkts)} packets to {out}")


if __name__ == "__main__":
    main()
