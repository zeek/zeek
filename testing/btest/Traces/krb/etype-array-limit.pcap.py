#!/usr/bin/env python3
"""Generate two Kerberos/TCP connections with oversized ETYPE arrays.

The first AS-REQ has 400 assigned encryption type INTEGERs (1,200 bytes).
The second has one 1,001-byte OCTET STRING instead of an Int32 (1,005 bytes).
Both exceed the ETYPE array's 1,000-byte limit.

Generated by OpenAI Codex GPT-6 sol using Scapy.
"""

from pathlib import Path

from scapy.all import IP, TCP, Ether, Raw, wrpcap

CLIENT = "192.0.2.1"
SERVER = "192.0.2.2"
SERVER_PORT = 88
BASE_TIME = 1_700_000_000.0
ETYPE_COUNT = 400
ETYPE_VALUES = (17, 18, 19, 20, 25, 26)


def ber_length(size: int) -> bytes:
    if size < 0x80:
        return bytes([size])

    encoded = size.to_bytes((size.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(encoded)]) + encoded


def ber_tlv(tag: int, value: bytes) -> bytes:
    return bytes([tag]) + ber_length(len(value)) + value


def many_etype_elements() -> bytes:
    # Repeat assigned etypes to exceed the byte limit with valid Int32 elements.
    return b"".join(
        ber_tlv(0x02, bytes([ETYPE_VALUES[index % len(ETYPE_VALUES)]]))
        for index in range(ETYPE_COUNT)
    )


def krb_as_request(etype_elements: bytes) -> bytes:
    etypes = ber_tlv(0x30, etype_elements)
    options = ber_tlv(0xA0, ber_tlv(0x03, b"\x00\x00\x00\x00\x00"))
    realm = ber_tlv(0xA2, ber_tlv(0x1B, b"EXAMPLE.COM"))
    till = ber_tlv(0xA5, ber_tlv(0x18, b"20300101000000Z"))
    nonce = ber_tlv(0xA7, ber_tlv(0x02, b"\x01"))
    body = ber_tlv(
        0xA4, ber_tlv(0x30, options + realm + till + nonce + ber_tlv(0xA8, etypes))
    )
    version = ber_tlv(0xA1, ber_tlv(0x02, b"\x05"))
    message_type = ber_tlv(0xA2, ber_tlv(0x02, b"\x0a"))
    request = ber_tlv(0x6A, ber_tlv(0x30, version + message_type + body))
    return len(request).to_bytes(4, "big") + request


def pkt(
    is_orig: bool,
    client_port: int,
    seq: int,
    ack: int,
    flags: str,
    payload: bytes = b"",
):
    if is_orig:
        src, dst, sport, dport = CLIENT, SERVER, client_port, SERVER_PORT
        eth_src, eth_dst = "02:00:00:00:00:01", "02:00:00:00:00:02"
    else:
        src, dst, sport, dport = SERVER, CLIENT, SERVER_PORT, client_port
        eth_src, eth_dst = "02:00:00:00:00:02", "02:00:00:00:00:01"

    packet = (
        Ether(src=eth_src, dst=eth_dst)
        / IP(src=src, dst=dst)
        / TCP(sport=sport, dport=dport, seq=seq, ack=ack, flags=flags)
    )

    if payload:
        packet = packet / Raw(payload)

    return packet


def connection_packets(client_port: int, request: bytes):
    client_seq, server_seq = 1000, 2000
    packets = [
        pkt(True, client_port, client_seq, 0, "S"),
        pkt(False, client_port, server_seq, client_seq + 1, "SA"),
        pkt(True, client_port, client_seq + 1, server_seq + 1, "A"),
    ]
    client_seq += 1
    server_seq += 1

    packets.append(pkt(True, client_port, client_seq, server_seq, "PA", request))
    client_seq += len(request)

    packets.append(pkt(True, client_port, client_seq, server_seq, "FA"))
    client_seq += 1
    packets.append(pkt(False, client_port, server_seq, client_seq, "FA"))
    server_seq += 1
    packets.append(pkt(True, client_port, client_seq, server_seq, "A"))
    return packets


def build_packets():
    many = krb_as_request(many_etype_elements())
    oversized = krb_as_request(ber_tlv(0x04, b"A" * 1001))
    return connection_packets(40000, many) + connection_packets(40001, oversized)


def main() -> None:
    packets = build_packets()

    for index, packet in enumerate(packets):
        packet.time = BASE_TIME + index * 0.001

    wrpcap(str(Path(__file__).with_suffix("")), packets)


if __name__ == "__main__":
    main()
