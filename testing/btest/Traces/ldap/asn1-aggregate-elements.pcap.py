#!/usr/bin/env python3
"""Generate an LDAP search-result entry with many ASN.1 aggregate children.

The result entry contains a PartialAttributeList sequence filled with minimal
ASN.1 NULL values. This exercises the aggregate element limit without requiring
a large trace.

Generated by GPT-5 Codex (OpenAI).
"""

from pathlib import Path

from scapy.all import IP, TCP, Ether, wrpcap

CLIENT_IP = "192.0.2.1"
SERVER_IP = "192.0.2.2"
CLIENT_PORT = 40000
SERVER_PORT = 389


def ber_length(size):
    if size < 0x80:
        return bytes([size])

    encoded = size.to_bytes((size.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(encoded)]) + encoded


def ber_tlv(tag, value):
    return bytes([tag]) + ber_length(len(value)) + value


def ldap_search_result(attribute_count=1000):
    attribute_values = b"\x05\x00" * attribute_count
    attributes = ber_tlv(0x30, attribute_values)
    result_entry = ber_tlv(0x64, ber_tlv(0x04, b"") + attributes)
    return ber_tlv(0x30, ber_tlv(0x02, b"\x01") + result_entry)


def packet(src, dst, sport, dport, flags, seq, ack, payload=b""):
    return (
        Ether(src="02:00:00:00:00:01", dst="02:00:00:00:00:02")
        / IP(src=src, dst=dst)
        / TCP(sport=sport, dport=dport, flags=flags, seq=seq, ack=ack)
        / payload
    )


def client_packet(flags, seq, ack, payload=b""):
    return packet(
        CLIENT_IP, SERVER_IP, CLIENT_PORT, SERVER_PORT, flags, seq, ack, payload
    )


def server_packet(flags, seq, ack, payload=b""):
    return packet(
        SERVER_IP, CLIENT_IP, SERVER_PORT, CLIENT_PORT, flags, seq, ack, payload
    )


def main():
    client_seq = 1000
    server_seq = 2000
    response = ldap_search_result()

    packets = [
        client_packet("S", client_seq, 0),
        server_packet("SA", server_seq, client_seq + 1),
        client_packet("A", client_seq + 1, server_seq + 1),
        server_packet("PA", server_seq + 1, client_seq + 1, response),
        client_packet("A", client_seq + 1, server_seq + 1 + len(response)),
    ]

    wrpcap(str(Path(__file__).with_suffix("")), packets)


if __name__ == "__main__":
    main()
