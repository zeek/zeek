#!/usr/bin/env python3
"""Generate an MQTT capture that triggers all subscription-related weirds.

Uses separate connections so each weird appears as a distinct log entry:
  Connection 1: mqtt_excessive_subscription_topics  (SUBSCRIBE with >5 topics)
  Connection 2: mqtt_excessive_subscription_topics  (UNSUBSCRIBE with >5 topics)
  Connection 3: MQTT_excessive_pending_subscriptions (>5 unacked subscribe messages)

Generated by Claude Opus 4.6.
"""

from pathlib import Path

from scapy.all import IP, TCP, Ether, Raw, wrpcapng

CLIENT = "10.10.0.1"
SERVER = "10.10.0.2"
SMAC = "02:00:00:00:00:01"
DMAC = "02:00:00:00:00:02"
DPORT = 1883
BASE_TS = 1_700_000_000.0
OUTPUT = Path(__file__).with_suffix("")


def enc_remaining_length(n):
    out = bytearray()
    while True:
        byte = n % 128
        n //= 128
        if n:
            byte |= 0x80
        out.append(byte)
        if not n:
            return bytes(out)


def mqtt_string(s):
    b = s.encode("ascii")
    return len(b).to_bytes(2, "big") + b


def mqtt_connect(client_id="zeek-test"):
    variable_header = (
        mqtt_string("MQTT")
        + b"\x04"  # protocol level 4 (MQTT 3.1.1)
        + b"\x02"  # connect flags: clean session
        + b"\x00\x3c"  # keep-alive 60s
    )
    payload = mqtt_string(client_id)
    body = variable_header + payload
    return bytes([0x10]) + enc_remaining_length(len(body)) + body


def mqtt_connack(return_code=0):
    return bytes([0x20, 0x02, 0x00, return_code])


def mqtt_subscribe(msg_id, topics):
    body = msg_id.to_bytes(2, "big")
    for topic in topics:
        body += mqtt_string(topic) + b"\x00"  # QoS 0
    return bytes([0x82]) + enc_remaining_length(len(body)) + body


def mqtt_unsubscribe(msg_id, topics):
    body = msg_id.to_bytes(2, "big")
    for topic in topics:
        body += mqtt_string(topic)
    return bytes([0xA2]) + enc_remaining_length(len(body)) + body


class Connection:
    def __init__(self, sport, cseq=1000, sseq=9000):
        self.sport = sport
        self.cseq = cseq
        self.sseq = sseq
        self.seq = cseq + 1
        self.ack = sseq + 1
        self.packets = []

    def pkt(self, src_ip, dst_ip, sport, dport, seq, ack, flags, payload, t):
        p = (
            Ether(src=SMAC, dst=DMAC)
            / IP(src=src_ip, dst=dst_ip)
            / TCP(sport=sport, dport=dport, flags=flags, seq=seq, ack=ack)
        )
        if payload:
            p = p / Raw(payload)
        p.time = BASE_TS + t
        return p

    def handshake(self, t):
        self.packets.append(
            self.pkt(CLIENT, SERVER, self.sport, DPORT, self.cseq, 0, "S", b"", t)
        )
        self.packets.append(
            self.pkt(
                SERVER,
                CLIENT,
                DPORT,
                self.sport,
                self.sseq,
                self.cseq + 1,
                "SA",
                b"",
                t + 0.0001,
            )
        )
        self.packets.append(
            self.pkt(
                CLIENT,
                SERVER,
                self.sport,
                DPORT,
                self.seq,
                self.ack,
                "A",
                b"",
                t + 0.0002,
            )
        )

    def send_client(self, payload, t):
        self.packets.append(
            self.pkt(
                CLIENT, SERVER, self.sport, DPORT, self.seq, self.ack, "PA", payload, t
            )
        )
        self.seq += len(payload)
        self.packets.append(
            self.pkt(
                SERVER,
                CLIENT,
                DPORT,
                self.sport,
                self.ack,
                self.seq,
                "A",
                b"",
                t + 0.0001,
            )
        )

    def send_server(self, payload, t):
        self.packets.append(
            self.pkt(
                SERVER, CLIENT, DPORT, self.sport, self.ack, self.seq, "PA", payload, t
            )
        )
        self.ack += len(payload)
        self.packets.append(
            self.pkt(
                CLIENT,
                SERVER,
                self.sport,
                DPORT,
                self.seq,
                self.ack,
                "A",
                b"",
                t + 0.0001,
            )
        )

    def teardown(self, t):
        self.packets.append(
            self.pkt(
                CLIENT, SERVER, self.sport, DPORT, self.seq, self.ack, "FA", b"", t
            )
        )
        self.packets.append(
            self.pkt(
                SERVER,
                CLIENT,
                DPORT,
                self.sport,
                self.ack,
                self.seq + 1,
                "FA",
                b"",
                t + 0.0001,
            )
        )
        self.packets.append(
            self.pkt(
                CLIENT,
                SERVER,
                self.sport,
                DPORT,
                self.seq + 1,
                self.ack + 1,
                "A",
                b"",
                t + 0.0002,
            )
        )


def main():
    all_packets = []
    t = 0.0
    many_topics = [f"t/{i:04d}" for i in range(6)]

    # Connection 1: SUBSCRIBE with >5 topics
    c1 = Connection(sport=40001)
    c1.handshake(t)
    t += 0.001
    c1.send_client(mqtt_connect("sub-topics"), t)
    t += 0.001
    c1.send_server(mqtt_connack(), t)
    t += 0.001
    c1.send_client(mqtt_subscribe(1, many_topics), t)
    t += 0.001
    c1.teardown(t)
    t += 0.001
    all_packets.extend(c1.packets)

    # Connection 2: UNSUBSCRIBE with >5 topics
    c2 = Connection(sport=40002)
    c2.handshake(t)
    t += 0.001
    c2.send_client(mqtt_connect("unsub-topics"), t)
    t += 0.001
    c2.send_server(mqtt_connack(), t)
    t += 0.001
    c2.send_client(mqtt_unsubscribe(1, many_topics), t)
    t += 0.001
    c2.teardown(t)
    t += 0.001
    all_packets.extend(c2.packets)

    # Connection 3: 101 SUBSCRIBE messages with no SUBACK
    c3 = Connection(sport=40003)
    c3.handshake(t)
    t += 0.001
    c3.send_client(mqtt_connect("pending"), t)
    t += 0.001
    c3.send_server(mqtt_connack(), t)
    t += 0.001
    for i in range(6):
        c3.send_client(mqtt_subscribe(i + 1, [f"p/{i:03d}"]), t)
        t += 0.001
    c3.teardown(t)
    t += 0.001
    all_packets.extend(c3.packets)

    wrpcapng(str(OUTPUT), all_packets)


if __name__ == "__main__":
    main()
