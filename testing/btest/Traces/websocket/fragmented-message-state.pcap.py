#!/usr/bin/env python3
"""Generate a fragmented WebSocket message followed by a standalone message.

A masked client-to-server data message is split into a fragmented start frame, a
run of empty continuation frames, and a large final continuation frame that is
itself spread across two TCP segments. A standalone text message follows so the
analyzer must resume from cached continuation state.

Generated by Codex (OpenAI); the accompanying PCAP is checked in for BTest.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from scapy.all import IP, TCP, Ether, Packet, Raw, wrpcap

CLIENT_IP = "192.0.2.10"
SERVER_IP = "192.0.2.20"
CLIENT_MAC = "02:00:00:00:00:10"
SERVER_MAC = "02:00:00:00:00:20"
CLIENT_PORT = 49152
SERVER_PORT = 8080
MASKING_KEY = b"\x11\x22\x33\x44"


def tcp_frame(
    payload: bytes,
    *,
    sequence: int,
    acknowledgment: int,
    flags: str,
    originator: bool,
    identifier: int,
) -> Packet:
    """Build one Ethernet, IPv4, and TCP frame."""
    source_ip, destination_ip = (
        (CLIENT_IP, SERVER_IP) if originator else (SERVER_IP, CLIENT_IP)
    )
    source_mac, destination_mac = (
        (CLIENT_MAC, SERVER_MAC) if originator else (SERVER_MAC, CLIENT_MAC)
    )
    source_port, destination_port = (
        (CLIENT_PORT, SERVER_PORT) if originator else (SERVER_PORT, CLIENT_PORT)
    )
    frame = (
        Ether(src=source_mac, dst=destination_mac)
        / IP(src=source_ip, dst=destination_ip, id=identifier, flags="DF")
        / TCP(
            sport=source_port,
            dport=destination_port,
            seq=sequence,
            ack=acknowledgment,
            flags=flags,
            window=65535,
        )
    )
    if payload:
        frame /= Raw(load=payload)
    return frame


def websocket_frame(opcode: int, finished: bool, payload: bytes) -> bytes:
    """Build one masked client-to-server WebSocket frame."""
    first = opcode | (0x80 if finished else 0)
    length = len(payload)
    if length < 126:
        header = bytes((first, 0x80 | length))
    elif length <= 0xFFFF:
        header = bytes((first, 0x80 | 126)) + length.to_bytes(2, "big")
    else:
        header = bytes((first, 0x80 | 127)) + length.to_bytes(8, "big")
    masked = bytes(
        value ^ MASKING_KEY[index % 4] for index, value in enumerate(payload)
    )
    return header + MASKING_KEY + masked


def build_packets() -> list[Packet]:
    """Build the TCP handshake, HTTP upgrade, and fragmented WebSocket message."""
    request = (
        b"GET /chat HTTP/1.1\r\n"
        b"Host: example.test\r\n"
        b"Upgrade: websocket\r\n"
        b"Connection: Upgrade\r\n"
        b"Sec-WebSocket-Key: dGhlIHNhbXBsZSBub25jZQ==\r\n"
        b"Sec-WebSocket-Version: 13\r\n\r\n"
    )
    response = (
        b"HTTP/1.1 101 Switching Protocols\r\n"
        b"Upgrade: websocket\r\n"
        b"Connection: Upgrade\r\n"
        b"Sec-WebSocket-Accept: s3pPLMBiTxaQ9kYGzzhZRbK+xOo=\r\n\r\n"
    )
    packets = [
        tcp_frame(
            b"",
            sequence=1000,
            acknowledgment=0,
            flags="S",
            originator=True,
            identifier=1,
        ),
        tcp_frame(
            b"",
            sequence=5000,
            acknowledgment=1001,
            flags="SA",
            originator=False,
            identifier=2,
        ),
        tcp_frame(
            b"",
            sequence=1001,
            acknowledgment=5001,
            flags="A",
            originator=True,
            identifier=3,
        ),
        tcp_frame(
            request,
            sequence=1001,
            acknowledgment=5001,
            flags="PA",
            originator=True,
            identifier=4,
        ),
        tcp_frame(
            response,
            sequence=5001,
            acknowledgment=1001 + len(request),
            flags="PA",
            originator=False,
            identifier=5,
        ),
    ]
    client_sequence = 1001 + len(request)
    server_sequence = 5001 + len(response)
    first = websocket_frame(2, False, b"start")
    continuations = websocket_frame(0, False, b"") * 32
    final = websocket_frame(0, True, b"A" * 2000)
    standalone = websocket_frame(1, True, b"done")
    segments = (first + continuations + final[:1000], final[1000:], standalone)
    for identifier, segment in enumerate(segments, start=6):
        packets.append(
            tcp_frame(
                segment,
                sequence=client_sequence,
                acknowledgment=server_sequence,
                flags="PA",
                originator=True,
                identifier=identifier,
            )
        )
        client_sequence += len(segment)
    return packets


def main() -> None:
    """Parse arguments and write the deterministic fragmented-message trace."""
    default_output = Path(__file__).with_suffix("")  # strip .py -> ...pcap
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path, default=default_output)
    args = parser.parse_args()

    packets = build_packets()
    for index, packet in enumerate(packets):
        packet.time = 1 + index / 1000
    wrpcap(str(args.output), packets)
    print(f"Wrote {len(packets)} packets to {args.output}")


if __name__ == "__main__":
    main()
